// Compiles contracts/SynodTest.sol and writes src/lib/synodTestArtifact.ts
// (ABI + creation bytecode). Run: npm run contract:build
import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync("contracts/SynodTest.sol", "utf8");
const out = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: { "SynodTest.sol": { content: source } },
      settings: {
        optimizer: { enabled: true, runs: 200 },
        evmVersion: "paris", // widest compatibility across Arbitrum/Orbit chains
        outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
      },
    })
  )
);

const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console.log(e.severity.toUpperCase() + ":", e.formattedMessage.trim());
if (errors.length) process.exit(1);

const c = out.contracts["SynodTest.sol"].SynodTest;
const ts = `// GENERATED by scripts/build-contract.mjs from contracts/SynodTest.sol. Do not edit.
export const synodTestAbi = ${JSON.stringify(c.abi, null, 2)} as const;

export const synodTestBytecode = "0x${c.evm.bytecode.object}" as const;
`;
writeFileSync("src/lib/synodTestArtifact.ts", ts);
console.log(`ok: ${c.abi.length} ABI entries, ${c.evm.bytecode.object.length / 2} bytes of bytecode`);
